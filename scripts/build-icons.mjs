// Builds Chhaya's icon set from Lucide (https://lucide.dev, ISC license).
//
// src/chhaya/icons/map.json maps our icon names to Lucide names. This script
// copies those SVG files into src/chhaya/icons/lucide/ (the vector library kept
// in the repo) and writes icons.generated.ts for the <Icon> component.
//
// Run after changing map.json:  npm run icons
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "src/chhaya/icons");
const src = join(root, "node_modules/lucide-static/icons");
const out = join(dir, "lucide");
const map = JSON.parse(readFileSync(join(dir, "map.json"), "utf8"));

mkdirSync(out, { recursive: true });
copyFileSync(join(root, "node_modules/lucide-static/LICENSE"), join(out, "LICENSE"));

const icons = {};
for (const [ours, lucide] of Object.entries(map)) {
  const file = join(src, `${lucide}.svg`);
  if (!existsSync(file)) throw new Error(`Lucide has no icon "${lucide}" (for "${ours}")`);
  copyFileSync(file, join(out, `${lucide}.svg`));
  const svg = readFileSync(file, "utf8").replace(/<!--[\s\S]*?-->/g, "");
  // Keep only the drawing inside <svg>…</svg>; <Icon> supplies the outer tag.
  icons[ours] = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/\s+/g, " ").trim();
}

const body = Object.entries(icons)
  .map(([k, v]) => `  ${/^[a-z]\w*$/i.test(k) ? k : JSON.stringify(k)}: ${JSON.stringify(v)},`)
  .join("\n");
writeFileSync(
  join(dir, "icons.generated.ts"),
  `// Generated by scripts/build-icons.mjs from Lucide (ISC). Do not edit; edit map.json and run \`npm run icons\`.\n\nexport const ICONS = {\n${body}\n} as const;\n`,
);
console.log(`${Object.keys(icons).length} icons written`);
